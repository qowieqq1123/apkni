if activitiesModel:isDontHandleSubType(subType)then
local reddotHanlde=activitiesModel:getDontHandleSubTypeReddot(subType)
if reddotHanlde then
return reddotHanlde(actId,subType,subId)
else
return false
end
end
loggerUtil.logErrFMT("子活动类型不是放弃处理类型：{0}",subType)
return false
end