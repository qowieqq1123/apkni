local catchSubCheckLookup={
[CATCH_TYPE.eMoney]=function(subs,...)
local params={...}
for i,v in ipairs(subs)do
if v==params[1]then
return true
end
end
return false
end,
[CATCH_TYPE.eActivityChange]=function(subs,...)
local params={...}
for i,v in ipairs(subs)do
if v==params[1]then
return true
end
end
return false
end,
}


function activitiesModel:disposeSubActReddotChange(catchType,...)
for subType,changes in pairs(subActReddotCatchLookup)do
local f=false
for i,v in ipairs(changes)do
local cType=v[1]
local subs=v[2]
if cType==catchType then
if subs~=nil then
local subCheck=catchSubCheckLookup[cType]
if subCheck then
f=subCheck(subs,...)
end
else
f=true
end
end
if f then
break
end
end
if f then
local all=activitiesModel:getAllActivities()
for act_id,actInfo in pairs(all)do
local sublist=actInfo:getSubList_subType(subType)
if#sublist>0 then

for i,sub_actInfo in ipairs(sublist)do
sub_actInfo:refreshReddot()
end
actInfo:refreshReddot()
end
end
end
end
end


function activitiesModel:disposeActSpeChange()
local all=activitiesModel:getAllActivities()
for act_id,actInfo in pairs(all)do
if actInfo:isKuafuType()then
local condition=actInfo:getActOpenDelayDays()
if condition then
actInfo:refreshCondition()
end
end
end
end


function activitiesModel:disposeActConditionChange(typo,...)
local params={...}
local len=#params
local all=activitiesModel:getAllActivities()
for act_id,actInfo in pairs(all)do

local condition=actInfo:getActCondition()
if condition then
local f=activitiesModel:checkCondition(condition,typo,params)
if f then
actInfo:refreshCondition()
end
end
end
end


function activitiesModel:disposeSubActConditionChange(typo,...)
local params={...}
local all=activitiesModel:getAllActivities()
for act_id,actInfo in pairs(all)do

local sublist=actInfo:get_sublist()
for i,sub_actInfo in ipairs(sublist)do
local condition=sub_actInfo:getConditionCfg()
if condition then
local f=activitiesModel:checkCondition(condition,typo,params)
if f then
sub_actInfo:refreshCondition()
end
end
end
end
end

function activitiesModel:checkConditionArgs(v,params)
local len1=#v
local len=#params
local mathArgs=len==(len1-1)
if len==0 then
return true
elseif mathArgs then
local t=table.sub(v,2,#v)
if not table.isDiff(t,params)then
return true
end
end
return false
end

function activitiesModel:checkCondition(condition,typo,params)
local f=false
for i,v in ipairs(condition)do
if v[1]==typo then
f=activitiesModel:checkConditionArgs(v,params)
end
if f then
return f
end
end
return f
end

